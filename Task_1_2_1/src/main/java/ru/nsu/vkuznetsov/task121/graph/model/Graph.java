package ru.nsu.vkuznetsov.task121.graph.model;

import java.util.Set;

/**
 * Граф с вершинами типа {@code V}.
 *
 * <p>Реализации могут использовать разные способы хранения:
 * матрицу смежности, матрицу инцидентности, список смежности и т.д.
 * Граф может быть ориентированным или неориентированным.
 *
 * @param <V> тип вершины
 */
public interface Graph<V> {

    /**
     * Добавляет вершину в граф. Если вершина уже есть, ничего не делает.
     *
     * @param vertex вершина
     */
    void addVertex(V vertex);

    /**
     * Удаляет вершину и все инцидентные ей рёбра.
     * Если вершины нет, ничего не делает.
     *
     * @param vertex вершина
     */
    void removeVertex(V vertex);

    /**
     * Проверяет наличие вершины в графе.
     *
     * @param vertex вершина
     * @return {@code true}, если вершина есть
     */
    boolean hasVertex(V vertex);

    /**
     * Возвращает множество всех вершин графа.
     *
     * @return множество вершин
     */
    Set<V> vertices();

    /**
     * Возвращает количество вершин в графе.
     *
     * @return число вершин
     */
    int vertexCount();

    /**
     * Добавляет ребро между вершинами.
     *
     * @param from начальная вершина
     * @param to   конечная вершина
     * @throws IllegalArgumentException если хотя бы одной из вершин нет в графе
     */
    void addEdge(V from, V to);

    /**
     * Удаляет ребро. Если ребра нет, ничего не делает.
     *
     * @param from начальная вершина
     * @param to   конечная вершина
     */
    void removeEdge(V from, V to);

    /**
     * Проверяет наличие ребра между вершинами.
     *
     * @param from начальная вершина
     * @param to   конечная вершина
     * @return {@code true}, если ребро есть
     */
    boolean hasEdge(V from, V to);

    /**
     * Возвращает множество всех рёбер графа.
     *
     * @return множество рёбер
     */
    Set<Edge<V>> edges();

    /**
     * Возвращает количество рёбер в графе.
     *
     * @return число рёбер
     */
    int edgeCount();

    /**
     * Возвращает соседей вершины. Для ориентированного графа — исходящих,
     * для неориентированного — всех смежных.
     * Если вершины нет, возвращает пустое множество.
     *
     * @param vertex вершина
     * @return множество соседей
     */
    Set<V> neighbors(V vertex);

    /**
     * Возвращает количество входящих рёбер вершины
     * (для неориентированного графа — степень).
     *
     * @param vertex вершина
     * @return число входящих рёбер
     */
    int inDegree(V vertex);

    /**
     * Возвращает количество исходящих рёбер вершины
     * (для неориентированного графа — степень).
     *
     * @param vertex вершина
     * @return число исходящих рёбер
     */
    int outDegree(V vertex);

    /**
     * Удаляет все вершины и рёбра.
     */
    void clear();
}